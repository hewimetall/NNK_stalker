#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn missions_cover_one_through_ten() {
        for id in 1..=10 {
            let mission = MissionDef::get(id).unwrap();
            assert_eq!(mission.id, id);
            assert!(!mission.title.is_empty());
            assert!(!mission.briefing.is_empty());
            assert!(!mission.objective.is_empty());
            assert!(!mission.completed_hint.is_empty());
        }
    }

    #[test]
    fn missions_reject_out_of_range_ids() {
        assert!(MissionDef::get(0).is_none());
        assert!(MissionDef::get(11).is_none());
        assert_eq!(MissionDef::validate_id(7), Ok(7));
        assert_eq!(
            MissionDef::validate_id(11),
            Err(DomainError::InvalidMissionId(11))
        );
    }
}
